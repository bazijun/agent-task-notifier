#!/usr/bin/env python3
"""Interactive Codex setup for Agent Task Notifier."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import getpass
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import time
import tomllib
from urllib import parse


ROOT = Path(__file__).resolve().parent
BRIDGE = ROOT / "notify_bridge.py"
ENV_FILE = ROOT / "notify.env"
DEFAULT_CODEX_HOME = Path(os.environ.get("CODEX_HOME", Path.home() / ".codex")).expanduser()
COCKPIT_CODEX_ROOT = Path.home() / ".antigravity_cockpit" / "instances" / "codex"
PYTHON = Path(sys.executable).resolve()


@dataclass(frozen=True)
class CodexTarget:
    home: Path
    label: str

    @property
    def config_file(self) -> Path:
        return self.home / "config.toml"

    @property
    def hooks_file(self) -> Path:
        return self.home / "hooks.json"


def ask(prompt: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    value = input(f"{prompt}{suffix}: ").strip()
    return value or default


def ask_secret(prompt: str, default: str = "") -> str:
    suffix = " [直接回车跳过]" if not default else " [直接回车保留原值]"
    value = getpass.getpass(f"{prompt}{suffix}: ").strip()
    return value or default


def load_existing_env() -> dict[str, str]:
    values: dict[str, str] = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            if line.strip() and not line.lstrip().startswith("#") and "=" in line:
                key, value = line.split("=", 1)
                values[key.strip()] = value.strip()
    return values


def write_env(values: dict[str, str]) -> None:
    lines = [
        "# Generated by setup.py. Keep this file private (mode 600).",
        "# Empty values disable a channel.",
    ]
    order = [
        "FEISHU_WEBHOOK_URL", "FEISHU_SECRET", "BARK_SERVER", "BARK_DEVICE_KEY",
        "BARK_DIRECT", "BARK_DIRECT_INTERFACE", "BARK_DIRECT_DNS", "BARK_DIRECT_IPS",
        "BARK_LEVEL", "BARK_GROUP", "BARK_ICON", "BARK_OPEN_URL",
        "BARK_HISTORY_URL", "BARK_HISTORY_LINK_TEXT", "BARK_SOUND",
        "WECOM_WEBHOOK_URL", "NTFY_SERVER", "NTFY_TOPIC", "NTFY_TOKEN",
        "WXPUSHER_APP_TOKEN", "WXPUSHER_UIDS", "IMESSAGE_TARGET",
    ]
    for key in order:
        if key in values:
            lines.append(f"{key}={values[key]}")
    temp = ENV_FILE.with_suffix(".env.tmp")
    temp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(temp, 0o600)
    temp.replace(ENV_FILE)


def backup(path: Path) -> Path | None:
    if not path.exists():
        return None
    target = path.with_name(f"{path.name}.before-task-notifier-{time.strftime('%Y%m%d-%H%M%S')}")
    shutil.copy2(path, target)
    return target


def toml_array(values: list[str]) -> str:
    # JSON string arrays are also valid TOML arrays.
    return json.dumps(values, ensure_ascii=False)


def label_for_home(home: Path) -> str:
    home = home.expanduser()
    if home == Path.home() / ".codex":
        return "codex-default"
    return f"codex-{home.name[:6]}"


def parse_instance(value: str) -> CodexTarget:
    """Parse either /path/to/CODEX_HOME or label=/path/to/CODEX_HOME."""
    if "=" in value:
        label, raw_home = value.split("=", 1)
        if not label.strip() or not raw_home.strip():
            raise ValueError("--instance must be [label=]CODEX_HOME")
    else:
        raw_home = value
        label = ""
    home = Path(raw_home).expanduser().resolve()
    return CodexTarget(home, label.strip() or label_for_home(home))


def discover_targets() -> list[CodexTarget]:
    homes = [Path.home() / ".codex"]
    if COCKPIT_CODEX_ROOT.exists():
        homes.extend(sorted(path for path in COCKPIT_CODEX_ROOT.iterdir() if (path / "config.toml").exists()))
    return [CodexTarget(home.resolve(), label_for_home(home)) for home in homes if (home / "config.toml").exists()]


def selected_targets(all_instances: bool, instances: list[str]) -> list[CodexTarget]:
    targets = discover_targets() if all_instances else []
    targets.extend(parse_instance(value) for value in instances)
    if not targets:
        home = DEFAULT_CODEX_HOME.resolve()
        targets = [CodexTarget(home, label_for_home(home))]
    # Explicit --instance entries come last and replace discovered labels.
    deduplicated: dict[Path, CodexTarget] = {}
    for target in targets:
        deduplicated[target.home] = target
    return list(deduplicated.values())


def compact_json(value: list[str]) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def is_bridge_command(command: object) -> bool:
    return isinstance(command, list) and any("notify_bridge.py" in str(item) for item in command)


def bridge_notify_command(target: CodexTarget, forward: list[str] | None = None) -> list[str]:
    command = [
        str(PYTHON),
        str(BRIDGE),
        "--codex-notify",
        "--instance-label",
        target.label,
        "--codex-home",
        str(target.home),
    ]
    if forward:
        command.extend(["--forward-command-json", compact_json(forward)])
    return command


def existing_bridge_forward(command: list[str]) -> list[str] | None:
    if "--forward-command-json" not in command:
        return None
    index = command.index("--forward-command-json")
    if index + 1 >= len(command):
        return None
    try:
        value = json.loads(command[index + 1])
    except json.JSONDecodeError:
        return None
    return value if isinstance(value, list) and all(isinstance(item, str) for item in value) else None


def merged_notify_command(current: object, target: CodexTarget) -> list[str]:
    """Preserve Cockpit's callback and any unrelated existing notify command."""
    if not isinstance(current, list) or not all(isinstance(item, str) for item in current):
        return bridge_notify_command(target)

    if current and Path(current[0]).name == "SkyComputerUseClient":
        base = list(current)
        previous: list[str] | None = None
        if "--previous-notify" in base:
            index = base.index("--previous-notify")
            if index + 1 < len(base):
                try:
                    decoded = json.loads(base[index + 1])
                    if isinstance(decoded, list) and all(isinstance(item, str) for item in decoded):
                        previous = decoded
                except json.JSONDecodeError:
                    previous = None
            del base[index : index + 2]
        forward = None if is_bridge_command(previous) else previous
        return base + ["--previous-notify", compact_json(bridge_notify_command(target, forward))]

    if is_bridge_command(current):
        return bridge_notify_command(target, existing_bridge_forward(current))
    return bridge_notify_command(target, current)


def install_notify(target: CodexTarget) -> str:
    target.home.mkdir(parents=True, exist_ok=True)
    config_file = target.config_file
    original = config_file.read_text(encoding="utf-8") if config_file.exists() else ""
    parsed = tomllib.loads(original) if original.strip() else {}
    current = parsed.get("notify")
    line = f"notify = {toml_array(merged_notify_command(current, target))}"
    pattern = re.compile(r"(?m)^notify\s*=.*$")
    if pattern.search(original):
        updated = pattern.sub(line, original, count=1)
    else:
        updated = line + "\n" + original
    if updated != original:
        backup(config_file)
        temp = config_file.with_suffix(".toml.task-notifier.tmp")
        temp.write_text(updated, encoding="utf-8")
        tomllib.loads(temp.read_text(encoding="utf-8"))
        temp.replace(config_file)
    return f"{target.label}: 完成通知已接入"


def install_permission_hook(target: CodexTarget) -> str:
    hooks_file = target.hooks_file
    data: dict = {}
    if hooks_file.exists():
        data = json.loads(hooks_file.read_text(encoding="utf-8"))
    data.setdefault("description", "User-level Codex lifecycle hooks.")
    hooks = data.setdefault("hooks", {})
    groups = hooks.setdefault("PermissionRequest", [])
    command = shlex.join([
        str(PYTHON),
        str(BRIDGE),
        "--hook",
        "--instance-label",
        target.label,
        "--codex-home",
        str(target.home),
    ])
    canonical_handler = {
        "type": "command",
        "command": command,
        "async": True,
        "timeout": 10,
        "statusMessage": "Sending remote approval notification",
    }
    cleaned_groups: list = []
    found_bridge = False
    for group in groups:
        if not isinstance(group, dict):
            cleaned_groups.append(group)
            continue
        cleaned_handlers: list = []
        for handler in group.get("hooks", []):
            handler_command = handler.get("command", "") if isinstance(handler, dict) else ""
            is_bridge = "notify_bridge.py" in handler_command and "--hook" in handler_command
            if is_bridge:
                if not found_bridge:
                    cleaned_handlers.append(canonical_handler)
                    found_bridge = True
                continue
            cleaned_handlers.append(handler)
        if cleaned_handlers:
            cleaned_group = dict(group)
            cleaned_group["hooks"] = cleaned_handlers
            cleaned_groups.append(cleaned_group)
    if not found_bridge:
        cleaned_groups.append({"hooks": [canonical_handler]})
    hooks["PermissionRequest"] = cleaned_groups

    original = json.loads(hooks_file.read_text(encoding="utf-8")) if hooks_file.exists() else None
    if data != original:
        backup(hooks_file)
        temp = hooks_file.with_suffix(".json.task-notifier.tmp")
        temp.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        temp.replace(hooks_file)
    return f"{target.label}: 等待授权通知已接入（请在该实例用 /hooks 信任）"


