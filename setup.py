def configure_channels(values: dict[str, str]) -> None:
    device = ask("接收设备（ios/android/other）", "ios").strip().lower()
    while device not in {"ios", "android", "other"}:
        print("请输入 ios、android 或 other。")
        device = ask("接收设备（ios/android/other）", "ios").strip().lower()
    default_channel = {"ios": "bark", "android": "ntfy", "other": "feishu"}[device]
    print("iPhone/iPad 可用 Bark；Android 推荐 ntfy，也可选飞书、企业微信等。")
    selected = ask("选择通道（逗号分隔：bark,feishu,wecom,ntfy,wxpusher,imessage）", default_channel)
    choices = {item.strip().lower() for item in selected.split(",") if item.strip()}

    if "feishu" in choices:
        values["FEISHU_WEBHOOK_URL"] = ask_secret("粘贴飞书自定义机器人 Webhook", values.get("FEISHU_WEBHOOK_URL", ""))
        values["FEISHU_SECRET"] = ask_secret("粘贴飞书签名密钥（未开启签名可留空）", values.get("FEISHU_SECRET", ""))
    if "bark" in choices:
        print("请先在 iPhone/iPad 安装 Bark App，并在 App 中复制推送地址或设备 Key。")
        credential = ask_secret(
            "粘贴 Bark App 复制的完整推送地址或设备 Key",
            values.get("BARK_DEVICE_KEY", ""),
        )
        server, device_key = parse_bark_credential(credential, values.get("BARK_SERVER", "https://api.day.app"))
        values["BARK_SERVER"] = server
        values["BARK_DEVICE_KEY"] = device_key
        values["BARK_LEVEL"] = values.get("BARK_LEVEL", "active")
        values["BARK_DIRECT"] = values.get("BARK_DIRECT", "1")
        values["BARK_GROUP"] = values.get("BARK_GROUP", "Codex")
        values["BARK_ICON"] = values.get(
            "BARK_ICON",
            "https://cdn.jsdelivr.net/gh/ilysenko/codex-desktop-linux@main/assets/codex.png",
        )
        values["BARK_OPEN_URL"] = values.get("BARK_OPEN_URL", "")
        values["BARK_HISTORY_URL"] = values.get("BARK_HISTORY_URL", "")
        values["BARK_HISTORY_LINK_TEXT"] = values.get("BARK_HISTORY_LINK_TEXT", "")
    if "wecom" in choices:
        values["WECOM_WEBHOOK_URL"] = ask_secret("粘贴企业微信群机器人 Webhook", values.get("WECOM_WEBHOOK_URL", ""))
    if "ntfy" in choices:
        print("请先在接收设备安装 ntfy App；配置后在 App 中订阅相同的 Topic。")
        values["NTFY_SERVER"] = ask("ntfy 服务器", values.get("NTFY_SERVER", "https://ntfy.sh"))
        values["NTFY_TOPIC"] = ask_secret("ntfy Topic（务必使用随机长字符串）", values.get("NTFY_TOPIC", ""))
        values["NTFY_TOKEN"] = ask_secret("ntfy Token（公开服务器可留空）", values.get("NTFY_TOKEN", ""))
    if "wxpusher" in choices:
        values["WXPUSHER_APP_TOKEN"] = ask_secret("WxPusher appToken", values.get("WXPUSHER_APP_TOKEN", ""))
        values["WXPUSHER_UIDS"] = ask_secret("WxPusher UID（多个用逗号分隔）", values.get("WXPUSHER_UIDS", ""))
    if "imessage" in choices:
        values["IMESSAGE_TARGET"] = ask("接收 iMessage 的手机号或 Apple ID 邮箱", values.get("IMESSAGE_TARGET", ""))


def parse_bark_credential(value: str, default_server: str = "https://api.day.app") -> tuple[str, str]:
    """Accept either a Bark device key or the full test/push URL copied by the app."""
    candidate = value.strip()
    if candidate.startswith(("https://", "http://")):
        parts = parse.urlsplit(candidate)
        path_parts = [part for part in parts.path.split("/") if part]
        if not parts.netloc or not path_parts:
            raise ValueError("Bark 推送地址中没有找到设备 Key")
        return f"{parts.scheme}://{parts.netloc}", path_parts[0]
    return default_server.rstrip("/"), candidate


def install_base(values: dict[str, str], targets: list[CodexTarget], include_hook: bool = True) -> None:
    # Legacy forwarding was shared across instances. Forwarding is now encoded
    # per target in config.toml, so a Cockpit instance cannot call another one's callback.
    values.pop("NOTIFIER_FORWARD_COMMAND_JSON", None)
    if values.get("BARK_DEVICE_KEY") or values.get("BARK_URL"):
        values.setdefault("BARK_SERVER", "https://api.day.app")
        values.setdefault("BARK_DIRECT", "1")
        values.setdefault("BARK_LEVEL", "active")
        values.setdefault("BARK_GROUP", "Codex")
        values.setdefault("BARK_SOUND", "")
    for target in targets:
        print(install_notify(target))
        print(install_user_prompt_hook(target))
        if include_hook:
            print(install_permission_hook(target))
    write_env(values)


def main() -> int:
    parser = argparse.ArgumentParser(description="Configure the Codex adapter for Agent Task Notifier")
    parser.add_argument(
        "--install-only",
        action="store_true",
        help="install the Codex event bridge without asking for channel credentials",
    )
    parser.add_argument("--no-hook", action="store_true", help="do not install the PermissionRequest hook")
    parser.add_argument(
        "--instance",
        action="append",
        default=[],
        metavar="[LABEL=]CODEX_HOME",
        help="install one instance; repeat for a batch",
    )
    parser.add_argument(
        "--all-instances",
        action="store_true",
        help="install ~/.codex and every Cockpit Codex instance",
    )
    parser.add_argument("--list-instances", action="store_true", help="list discovered instances and exit")
    args = parser.parse_args()

    targets = selected_targets(args.all_instances, args.instance)
    if args.list_instances:
        for target in discover_targets():
            print(f"{target.label}\t{target.home}")
        return 0

    print("Agent Task Notifier — Codex 接入向导\n")
    print("向导输入的渠道凭据保存在项目目录的 notify.env，文件权限设为 600。")
    values = load_existing_env()
    if args.install_only:
        install_base(values, targets, include_hook=not args.no_hook)
        print(f"已接入 {len(targets)} 个 Codex 实例；重启实例后生效。")
        return 0

    configure_channels(values)
    write_env(values)

    installed = ask("安装到所选 Codex 实例", "Y").lower() in {"y", "yes", "是"}
    if installed:
        include_hook = ask("同时启用“等待授权”提醒", "Y").lower() in {"y", "yes", "是"}
        install_base(values, targets, include_hook=include_hook)

    print("\n正在发送测试消息……")
    test_command = [str(PYTHON), str(BRIDGE), "--test", "--instance-label", targets[0].label]
    result = subprocess.run(test_command, text=True)
    if result.returncode == 0:
        if installed:
            print("\n测试通知已发送。重启已接入的 Codex 实例；首次使用新增 Hook 时，在对应实例输入 /hooks 并信任。")
        else:
            print("\n测试通知已发送。尚未安装 Codex 回调；需要任务通知时，运行 python3 setup.py --install-only。")
    else:
        print("\n测试未通过。请检查 notifier.log；配置已保留，可重新运行本向导。")
    return result.returncode


if __name__ == "__main__":
    raise SystemExit(main())
